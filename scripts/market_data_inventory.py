"""Market data provider inventory (spec market-data-provider-inventory), generated from services.market_data_update.endpoints() and
core.runtime.ingestion_authority.SOURCE_IDS; no network. Terms of use are never inferred: TERMS_NOT_VERIFIED_BY_AGENT unless cited.

python scripts/market_data_inventory.py  -> docs/research/2026-11-09-market-data-autonomy-and-reference-research-v1/market_data_provider_inventory.md
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/research/2026-11-09-market-data-autonomy-and-reference-research-v1/market_data_provider_inventory.md'
DATASETS = ('prices_volume', 'financials', 'monthly_revenue', 'corporate_actions', 'benchmark')
TABLE = {'prices_volume': 'daily_market_data', 'financials': 'financial_statements', 'monthly_revenue': 'monthly_revenue'}


def rows(day='2026-11-05') -> list:
    from core.runtime import public_data
    from core.runtime.ingestion_authority import SOURCE_IDS
    from services.market_data_update import endpoints
    out = []
    for scope in ('TWSE_ONLY', 'ALL'):
        for name in DATASETS:
            for spec in endpoints(name, day, scope):
                if 'restricted' in spec:
                    out.append((scope, name, spec['url'], f"restricted:{spec['restricted']}", 'RESTRICTED (separate authorization)', '-'))
                    continue
                ctx = public_data.context(spec['url'], method=spec['method'], params=spec.get('params'), data=spec.get('data'))
                source = SOURCE_IDS.get(ctx.dataset, f'{ctx.dataset} (not an ingestion source)')
                out.append((scope, name, ctx.url, source, 'market_data_ingestion grant, 1 use per HTTP, >= 3.2 s', TABLE.get(name, 'file cache only')))
    return out


def write() -> Path:
    lines = ['# Market data provider inventory', '', 'Generated by scripts/market_data_inventory.py (no network). API key: none for every source. '
             'Terms of use: TERMS_NOT_VERIFIED_BY_AGENT (no official terms are cited in the repository).', '',
             '| scope | dataset | endpoint | source id | authorization | database target |', '|---|---|---|---|---|---|']
    lines += [f'| {" | ".join(row)} |' for row in dict.fromkeys(rows())]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return OUT


if __name__ == '__main__':
    import sys
    sys.path.insert(0, str(ROOT))
    print(write())
